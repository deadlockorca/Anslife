import type { LanguageCode } from './language';

type NonVietnameseLanguage = Exclude<LanguageCode, 'vn'>;
type TranslationMap = Record<string, string>;

function withPositionCounts(labels: Record<NonVietnameseLanguage, string>): Record<NonVietnameseLanguage, TranslationMap> {
  return Object.fromEntries(
    Object.entries(labels).map(([language, label]) => [
      language,
      Object.fromEntries(
        Array.from({ length: 80 }, (_, index) => {
          const count = index + 1;
          return [`${count} vị trí`, `${count} ${label}`];
        }),
      ),
    ]),
  ) as Record<NonVietnameseLanguage, TranslationMap>;
}

